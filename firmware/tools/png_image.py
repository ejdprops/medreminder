#!/usr/bin/env python3
"""Convert an opaque PNG to an LVGL RGB565 image C file (for logos and other full-color art).

Alpha is flattened onto --bg, so pick the color of the screen the image sits on.

Needs Pillow (not part of the IDF env; use the same throwaway venv as svg_icons.py):
    /tmp/iconvenv/bin/python tools/png_image.py <png> --name img_averak_logo --height 168 \\
        --bg 0b0d14 --out main/images

Writes <out>/<name>.c and adds LV_IMAGE_DECLARE(<name>) to <out>/images.h. Output is committed.
"""
import argparse
import os
import re

from PIL import Image


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("png")
    ap.add_argument("--name", required=True)
    ap.add_argument("--height", type=int, required=True)
    ap.add_argument("--bg", default="000000", help="hex RGB the alpha is flattened onto")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    src = Image.open(a.png).convert("RGBA")
    w = round(src.width * a.height / src.height)
    bg = Image.new("RGBA", src.size, "#" + a.bg)
    img = Image.alpha_composite(bg, src).convert("RGB").resize((w, a.height), Image.LANCZOS)

    data = bytearray()
    raw = img.tobytes()
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))  # little-endian, LVGL native RGB565

    os.makedirs(a.out, exist_ok=True)
    rows = []
    stride = w * 2
    for y in range(a.height):
        row = data[y * stride:(y + 1) * stride]
        for i in range(0, len(row), 24):
            rows.append("    " + ", ".join(f"0x{b:02x}" for b in row[i:i + 24]) + ",")
    src_rel = os.path.basename(a.png)
    with open(os.path.join(a.out, f"{a.name}.c"), "w") as f:
        f.write(f"/* Generated by tools/png_image.py from {src_rel} ({w}x{a.height} RGB565, bg #{a.bg}). "
                "Do not edit. */\n")
        f.write('#if __has_include("lvgl.h")\n#include "images.h"\n\n')
        f.write(f"static const uint8_t {a.name}_map[] = {{\n" + "\n".join(rows) + "\n};\n\n")
        f.write(f"const lv_image_dsc_t {a.name} = {{\n"
                "    .header = {\n"
                "        .magic = LV_IMAGE_HEADER_MAGIC,\n"
                "        .cf = LV_COLOR_FORMAT_RGB565,\n"
                f"        .w = {w},\n"
                f"        .h = {a.height},\n"
                f"        .stride = {stride},\n"
                "    },\n"
                f"    .data_size = sizeof({a.name}_map),\n"
                f"    .data = {a.name}_map,\n"
                "};\n#endif\n")

    hdr = os.path.join(a.out, "images.h")
    names = set()
    if os.path.exists(hdr):
        names = set(re.findall(r"LV_IMAGE_DECLARE\((\w+)\);", open(hdr).read()))
    names.add(a.name)
    with open(hdr, "w") as f:
        f.write("/* Generated by tools/png_image.py. */\n#pragma once\n#include \"lvgl.h\"\n\n")
        f.write("\n".join(f"LV_IMAGE_DECLARE({n});" for n in sorted(names)) + "\n")
    print(f"wrote {a.name} ({w}x{a.height}, {len(data)} bytes) to {a.out}")


if __name__ == "__main__":
    main()
