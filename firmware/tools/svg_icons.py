#!/usr/bin/env python3
"""Render stroke-style 24x24 SVG icons (Feather/Lucide style) to LVGL A8 image C files.

A8 = alpha only; the color comes from the LVGL style (image_recolor), so one icon serves any color.
Supports the subset these icons use: path, polyline, line, rect (rx), circle; stroke-width,
fill="currentColor" with fill-opacity. Not a general SVG renderer.

Needs Pillow and svg.path (not part of the IDF env; use a throwaway venv):
    python -m venv /tmp/iconvenv && /tmp/iconvenv/bin/pip install pillow svg.path
    /tmp/iconvenv/bin/python tools/svg_icons.py --size 20 main/icons/svg/*.svg --out main/icons

Writes <out>/icon_<name>.c per SVG and <out>/icons.h. The generated files are committed.
"""
import argparse
import math
import os
import re
import xml.etree.ElementTree as ET

from PIL import Image, ImageChops, ImageDraw
from svg.path import parse_path

SS = 8  # supersampling factor


def num(el, key, default=0.0):
    v = el.get(key)
    return float(v) if v is not None else default


def path_subpaths(d):
    """Split a path into polylines (list of (x, y)) and whether each is closed."""
    out, cur = [], []
    for seg in parse_path(d):
        kind = type(seg).__name__
        if kind == "Move":
            if len(cur) > 1:
                out.append((cur, False))
            cur = [(seg.start.real, seg.start.imag)]
            continue
        n = 1 if kind in ("Line", "Close") else max(8, int(seg.length() * 4))
        for i in range(1, n + 1):
            p = seg.point(i / n)
            cur.append((p.real, p.imag))
        if kind == "Close":
            out.append((cur, True))
            cur = [cur[-1]]
    if len(cur) > 1:
        out.append((cur, False))
    return out


def rect_points(x, y, w, h, r):
    if r <= 0:
        return [(x, y), (x + w, y), (x + w, y + h), (x, y + h), (x, y)]
    pts = []
    for cx, cy, a0 in ((x + w - r, y + r, -90), (x + w - r, y + h - r, 0), (x + r, y + h - r, 90), (x + r, y + r, 180)):
        for i in range(9):
            a = math.radians(a0 + i * 90 / 8)
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    pts.append(pts[0])
    return pts


def circle_points(cx, cy, r):
    return [(cx + r * math.cos(2 * math.pi * i / 48), cy + r * math.sin(2 * math.pi * i / 48)) for i in range(49)]


def shapes(root):
    """Yield (points, closed, fill_opacity) per shape."""
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        fill = el.get("fill")
        fo = float(el.get("fill-opacity", "1")) if fill and fill != "none" else 0.0
        if tag == "path":
            for pts, closed in path_subpaths(el.get("d")):
                yield pts, closed, fo
        elif tag == "polyline":
            vals = [float(v) for v in re.split(r"[\s,]+", el.get("points").strip())]
            yield list(zip(vals[0::2], vals[1::2])), False, fo
        elif tag == "line":
            yield [(num(el, "x1"), num(el, "y1")), (num(el, "x2"), num(el, "y2"))], False, fo
        elif tag == "rect":
            yield rect_points(num(el, "x"), num(el, "y"), num(el, "width"), num(el, "height"), num(el, "rx")), True, fo
        elif tag == "circle":
            yield circle_points(num(el, "cx"), num(el, "cy"), num(el, "r")), True, fo


def render(svg_file, size):
    root = ET.parse(svg_file).getroot()
    vb = [float(v) for v in root.get("viewBox", "0 0 24 24").split()]
    stroke_w = float(root.get("stroke-width", "2"))
    scale = size * SS / vb[2]
    big = size * SS
    fill_layer = Image.new("L", (big, big), 0)
    stroke_layer = Image.new("L", (big, big), 0)
    fd, sd = ImageDraw.Draw(fill_layer), ImageDraw.Draw(stroke_layer)
    w = stroke_w * scale
    for pts, closed, fo in shapes(root):
        p = [((x - vb[0]) * scale, (y - vb[1]) * scale) for x, y in pts]
        if fo > 0 and len(p) > 2:
            fd.polygon(p, fill=int(255 * fo))
        sd.line(p, fill=255, width=max(1, round(w)))
        for x, y in p:  # round joins and caps
            sd.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=255)
    alpha = ImageChops.lighter(fill_layer, stroke_layer)
    return alpha.resize((size, size), Image.BOX)


def write_c(name, img, out_dir):
    size = img.width
    data = list(img.tobytes())
    rows = [", ".join(f"0x{v:02x}" for v in data[r * size:(r + 1) * size]) for r in range(size)]
    body = ",\n    ".join(rows)
    src = f"""/* Generated by tools/svg_icons.py from main/icons/svg/{name}.svg. Do not edit. */
#if __has_include("lvgl.h")
#include "icons.h"

static const uint8_t icon_{name}_map[] = {{
    {body}
}};

const lv_image_dsc_t icon_{name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_A8,
        .w = {size},
        .h = {size},
        .stride = {size},
    }},
    .data_size = sizeof(icon_{name}_map),
    .data = icon_{name}_map,
}};
#endif
"""
    with open(os.path.join(out_dir, f"icon_{name}.c"), "w") as f:
        f.write(src)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("svgs", nargs="+")
    ap.add_argument("--size", type=int, default=20)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    names = []
    for svg_file in sorted(a.svgs):
        name = os.path.splitext(os.path.basename(svg_file))[0].replace("-", "_")
        write_c(name, render(svg_file, a.size), a.out)
        names.append(name)
    decls = "\n".join(f"LV_IMAGE_DECLARE(icon_{n});" for n in names)
    with open(os.path.join(a.out, "icons.h"), "w") as f:
        f.write(f"""/* Generated by tools/svg_icons.py. Do not edit. A8 images: set image_recolor + recolor_opa. */
#pragma once
#include "lvgl.h"

{decls}
""")
    print(f"wrote {len(names)} icons ({a.size}px) to {a.out}: {', '.join(names)}")


if __name__ == "__main__":
    main()
