#!/usr/bin/env bash
# Generate the UI's LVGL fonts from Inter static TTFs (https://github.com/rsms/inter, OFL-1.1).
#   tools/gen_fonts.sh <dir with Inter-Regular.ttf, Inter-SemiBold.ttf, Inter-Bold.ttf>
# Inter 4.1: the release zip's extras/ttf/ folder. Needs Node (npx); output is committed.
set -euo pipefail
cd "$(dirname "$0")/.."

TTF_DIR="${1:?usage: $0 <Inter ttf dir>}"
OUT=main/fonts
RANGE="0x20-0x7E,0xB7,0x2713"   # ASCII, middle dot, check mark
mkdir -p "$OUT"

# size weight name
FONTS=(
    "8 Regular inter_8"
    "9 Regular inter_9"
    "9 SemiBold inter_9_semibold"
    "10 SemiBold inter_10_semibold"
    "11 SemiBold inter_11_semibold"
    "12 SemiBold inter_12_semibold"
    "12 Bold inter_12_bold"
    "13 SemiBold inter_13_semibold"
    "14 SemiBold inter_14_semibold"
    "16 SemiBold inter_16_semibold"
    "16 Bold inter_16_bold"
    "23 SemiBold inter_23_semibold"
)

decls=""
for f in "${FONTS[@]}"; do
    read -r size weight name <<<"$f"
    npx --yes lv_font_conv@1.5.3 --font "$TTF_DIR/Inter-$weight.ttf" -r "$RANGE" --size "$size" --bpp 4 \
        --format lvgl --no-compress --lv-include lvgl.h --lv-font-name "$name" -o "$OUT/$name.c"
    # Drop the local TTF path from the header; guard for boards without LVGL.
    sed -i.bak -e "s|--font [^ ]*/Inter-$weight.ttf|--font Inter-$weight.ttf (Inter 4.1)|" \
        -e '1i\
#if __has_include("lvgl.h") /* generated by tools/gen_fonts.sh */' "$OUT/$name.c"
    rm -f "$OUT/$name.c.bak"
    echo "#endif" >>"$OUT/$name.c"
    decls+="LV_FONT_DECLARE($name);"$'\n'
done

cat >"$OUT/fonts.h" <<EOF
/* Generated by tools/gen_fonts.sh. Inter 4.1 (OFL-1.1); glyphs: ASCII, U+00B7, U+2713. */
#pragma once
#include "lvgl.h"

$decls
EOF
echo "wrote ${#FONTS[@]} fonts to $OUT"
